/// Reader schemas describe stored fields, while `EcmwfVariable` remains the download union.
/// Share storage metadata so reader and downloader filenames, units and interpolation agree.
protocol EcmwfReaderVariable: GenericVariable, CaseIterable {}

extension EcmwfReaderVariable {
    private var storageVariable: EcmwfVariable { EcmwfVariable(rawValue: rawValue)! }

    var omFileName: (file: String, level: Int) { storageVariable.omFileName }
    var scalefactor: Float { storageVariable.scalefactor }
    var interpolation: ReaderInterpolation { storageVariable.interpolation }
    var unit: SiUnit { storageVariable.unit }
    var isElevationCorrectable: Bool { storageVariable.isElevationCorrectable }
    var storePreviousForecast: Bool { storageVariable.storePreviousForecast }
}

